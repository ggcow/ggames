// Hasard reproductible pour la génération des niveaux : un niveau doit être identique sur tous les appareils
// et sur le serveur, qui le régénère pour rejouer chaque partie.

/** Générateur pseudo-aléatoire mulberry32 : même suite sur tous les appareils pour une graine donnée. */
export function createRandom(seed: number): () => number {
  let state = seed | 0;
  return () => {
    state = (state + 0x6d2b79f5) | 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Mélange `items` sur place (Fisher-Yates) avec `random`. */
export function shuffle<T>(items: T[], random: () => number): T[] {
  for (let i = items.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [items[i], items[j]] = [items[j] as T, items[i] as T];
  }
  return items;
}
